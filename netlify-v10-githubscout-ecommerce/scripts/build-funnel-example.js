'use strict'
// Writes assets/funnel-example.js: the "see an example result" data used by the
// conversational funnel pages. It is produced by the real report engine on the
// same representative stack as sample-report.html (Rebuy, Klaviyo, Yotpo,
// Gorgias, Judge.me), at teaser depth, so the example a visitor sees is exactly
// what a free scan of such a store returns. Re-run after any engine or ruleset
// change: `bun scripts/build-funnel-example.js`.

const fs = require('node:fs')
const path = require('node:path')
const { parseHtmlEvidence } = require('../netlify/functions/lib/adapters.js')
const agg = require('../netlify/functions/lib/aggregate.js')

const html = [
  '<script src="https://cdn.rebuyengine.com/a.js"></script>',
  '<script src="https://static.klaviyo.com/onsite/js/klaviyo.js"></script>',
  '<div class="yotpo-widget"></div><script src="https://staticw2.yotpo.com/x.js"></script>',
  '<script src="https://config.gorgias.chat/x.js"></script>',
  '<script src="https://cdn.judge.me/widget.js"></script><div class="judgeme"></div>',
].join('')

const scan = {
  pages: [
    { sourceId: 'home-html', url: 'https://example-store.com/', evidence: parseHtmlEvidence(html) },
    {
      sourceId: 'product-html',
      url: 'https://example-store.com/products/example',
      evidence: parseHtmlEvidence(html),
    },
  ],
  scriptHosts: [
    'cdn.rebuyengine.com',
    'static.klaviyo.com',
    'staticw2.yotpo.com',
    'config.gorgias.chat',
    'cdn.judge.me',
  ],
  dnsInfo: { txt: ['klaviyo-site-verification=example'], mx: [] },
  robots: null,
  shopifyConfirmed: true,
  sourcesLive: require('../netlify/functions/lib/adapters.js').liveSourceCount(),
  sourcesSucceeded: 8,
  sourcesPlanned: [],
  sources: [],
  checkoutProviders: ['Shop Pay / Shopify Checkout'],
}

function buildExample() {
  return agg.buildReport(scan, {}, 'teaser')
}

function render(report) {
  return (
    '// Generated by scripts/build-funnel-example.js from the real report engine.\n' +
    '// Example store, not a real merchant. Do not edit by hand.\n' +
    'window.FUNNEL_EXAMPLE = ' +
    JSON.stringify(report, null, 2) +
    ';\n'
  )
}

const OUT = path.join(__dirname, '..', 'assets', 'funnel-example.js')

if (require.main === module) {
  const report = buildExample()
  fs.writeFileSync(OUT, render(report))
  process.stdout.write(
    `wrote assets/funnel-example.js (${report.summary.detectedCount} apps, ${report.overlaps.length} overlap)\n`,
  )
}

module.exports = { buildExample, render, OUT }
